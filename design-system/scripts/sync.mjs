// Copies the design system into an app as one file:
//   node scripts/sync.mjs <output-file> <brand>
//   node scripts/sync.mjs ../inspo-browser/public/ds.css swatchbook
//
// Apps get a copy (not a link) so each one deploys on its own. Re-run this
// after changing the design system; the header records the version.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const [out, brand] = process.argv.slice(2);
const brandFile = join(root, "brands", `${brand}.css`);
if (!out || !brand || !existsSync(brandFile)) {
  console.error("Usage: node scripts/sync.mjs <output-file> <brand>   (brands: blupi, swatchbook)");
  process.exit(1);
}

const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const read = (f) => readFileSync(join(root, f), "utf8").trim();
const header = `/* Design system v${version} (${brand}). Generated by design-system/scripts/sync.mjs: edit the design system, not this file. */`;
// tokens.css starts with the font @import, which must stay first after the header comment
writeFileSync(resolve(out), [header, read("tokens.css"), read("components.css"), read(`brands/${brand}.css`)].join("\n\n") + "\n");
console.log(`Wrote ${out} (v${version}, ${brand})`);
